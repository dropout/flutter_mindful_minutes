import 'package:flutter/services.dart';
import 'package:flutter_mindful_minutes/flutter_mindful_minutes.g.dart';
import 'package:flutter_mindful_minutes/src/exceptions.dart';
import 'package:meta/meta.dart';

export 'package:flutter_mindful_minutes/flutter_mindful_minutes.g.dart' show AuthorizationStatus, RequestStatusForAuthorization, AuthorizationResult;
export 'package:flutter_mindful_minutes/src/exceptions.dart' hide MindfulMinutesErrorCodes, mapPlatformException;

/// FlutterMindfulMinutes is a Flutter Plugin that allows you
/// to write mindful minutes to the system on Android and iOS.
///
/// Every method throws a [FlutterMindfulMinutesException] subtype on failure.
class FlutterMindfulMinutes {

  FlutterMindfulMinutes() : _api = FlutterMindfulMinutesHostApi();

  @visibleForTesting
  FlutterMindfulMinutes.withApi(FlutterMindfulMinutesHostApi api) : _api = api;

  /// The host API for communicating with the native platform.
  /// This is generated by Pigeon and should not be modified manually.
  final FlutterMindfulMinutesHostApi _api;

  /// Checks if the mindful minutes API is available on the current device.
  ///
  /// Completes normally when it is available, otherwise throws a
  /// [MindfulMinutesUnavailableException] subtype describing the reason:
  /// [HealthDataUnavailableException], [ProviderUpdateRequiredException],
  /// [MindfulnessNotSupportedException] or [ActivityNotSupportedException].
  Future<void> checkAvailability() => _guard(_api.checkAvailability);

  /// Checks if the app has permission to write mindful minutes.
  ///
  /// On iOS throws [MissingEntitlementException] when the HealthKit
  /// capability is not enabled.
  Future<AuthorizationStatus> getAuthorizationStatus() =>
    _guard(_api.getAuthorizationStatus);

  /// Checks if the app should request permission to write mindful minutes.
  ///
  /// On iOS throws [MissingEntitlementException] when the HealthKit
  /// capability is not enabled.
  Future<RequestStatusForAuthorization> getRequestForAuthorizationStatus() =>
    _guard(_api.getRequestForAuthorizationStatus);

  /// Requests to open the system dialog/sheet to request permission to write and read mindful minutes.
  /// Note:
  /// - the result doesn't mean that the user granted permission
  /// - the result doesn't mean that the system dialog/sheet was shown (it may have been suppressed by the system)
  ///
  /// Throws [MissingEntitlementException] (iOS), [ActivityNotSupportedException],
  /// [MindfulnessNotSupportedException] or
  /// [MissingPermissionDeclarationException] (Android) on misconfiguration.
  Future<bool> requestAuthorization() => _guard(_api.requestAuthorization);

  /// Writes mindful minutes to the system.
  /// [startTime] and [endTime] are the start and end times of
  /// mindful minutes exercised.
  ///
  /// Throws [MissingEntitlementException] (iOS) or
  /// [MissingPermissionDeclarationException] (Android) on misconfiguration.
  // Communication between platforms is done in seconds.
  Future<void> writeMindfulMinutes(DateTime startTime, DateTime endTime) =>
    _guard(() => _api.writeMindfulMinutes(
      (startTime.millisecondsSinceEpoch / 1000).toInt(),
      (endTime.millisecondsSinceEpoch / 1000).toInt(),
    ));

  /// Runs [call] and converts platform errors to [FlutterMindfulMinutesException]s.
  Future<T> _guard<T>(Future<T> Function() call) async {
    try {
      return await call();
    } on PlatformException catch (e, stackTrace) {
      Error.throwWithStackTrace(mapPlatformException(e), stackTrace);
    }
  }

}
